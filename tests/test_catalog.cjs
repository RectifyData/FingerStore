'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync(__dirname+'/../webroot/catalog.js','utf8');
const page=fs.readFileSync(__dirname+'/../webroot/index.html','utf8');
const ctx={window:{}};
vm.runInNewContext(source,ctx,{timeout:2500});
const list=ctx.window.FINGERSTORE_CATALOG;
const make=ctx.window.FINGERSTORE_CATALOG_FP;
const build=ctx.window.FINGERSTORE_CATALOG_BUILD;
const sourceUrl=ctx.window.FINGERSTORE_CATALOG_SOURCE;
assert.equal(list.length,100,'100 stock device profiles, no fabricated filler');
assert(Object.isFrozen(list));
assert.equal(new Set(Array.from(list,d=>d.id)).size,100);
assert.equal(new Set(Array.from(list,d=>d.manufacturer+'|'+d.model)).size,100);
assert.equal(new Set(Array.from(list,d=>d.fingerprint)).size,100);
assert(list.some(d=>d.model==='Pixel 5'));
assert(list.some(d=>d.model==='Pixel 4 XL'));
assert(list.some(d=>d.model==='SM-G975F'&&d.label.includes('S10 Plus')));
assert(!list.some(d=>d.label.includes('Pixel 5 XL')));
assert(sourceUrl.includes('MagiskHidePropsConf'));
const re=/^[^/\s]+\/[^/\s]+\/[^:\s]+:\d+(?:\.\d+)*\/[^/\s]+\/[^:\s]+:user\/release-keys$/;
let variants=0;
for(const d of list){
 assert(Object.isFrozen(d));
 assert(Object.isFrozen(d.builds));
 assert(d.model&&d.manufacturer&&d.product&&d.device&&d.label);
 assert.equal(d.fingerprint,make(d,d.defaultVersion));
 assert.equal(Object.keys(d.builds).includes(d.defaultVersion),true);
 assert.equal(make(d,'16'),'', 'never manufacture unsupported Android 16');
 for(const [version,stock] of Object.entries(d.builds)){
  variants++;
  assert(Object.isFrozen(stock));
  assert(re.test(stock.fingerprint),stock.fingerprint);
  assert.equal(stock.fingerprint,make(d,version));
  assert.equal(build(d,version).fingerprint,stock.fingerprint);
  assert(stock.fingerprint.startsWith(d.brand+'/'+d.product+'/'+d.device+':'+version+'/'));
  assert(!stock.fingerprint.includes('/DEMO')&&!stock.fingerprint.includes('demo_'));
  assert(stock.patch===''||/^\d{4}-\d{2}-\d{2}$/.test(stock.patch));
 }
}
const pixel5=list.find(d=>d.model==='Pixel 5');
assert(make(pixel5,'11'));
assert(make(pixel5,'12'));
assert.equal(make(pixel5,'13'),'','no fake Pixel 5 Android 13 build');
assert.equal(build(pixel5,'13'),null);
assert(variants>=100);
assert(page.includes('Google+Sans+Flex'));
assert(page.includes('@material/web/'));
assert(page.includes('<md-outlined-select'));
assert(page.includes('Recorded Android version'));
assert(!page.includes('id="ssaidTitle"')&&!page.includes('id="keyboxTitle"'));
assert(!page.includes('ssaidctl.sh')&&!page.includes('keyboxctl.sh'));
console.log('PASS: 100 real sourced stock entries, '+variants+' authentic build variants, no synthesized versions, Material 3');
