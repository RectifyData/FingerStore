'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync(__dirname+'/../webroot/catalog.js','utf8');
const page=fs.readFileSync(__dirname+'/../webroot/index.html','utf8');
const ctx={window:{}};
vm.runInNewContext(source,ctx,{timeout:7000});
const list=ctx.window.FINGERSTORE_CATALOG;
const make=ctx.window.FINGERSTORE_CATALOG_FP;
const get=ctx.window.FINGERSTORE_CATALOG_BUILD;
const all=ctx.window.FINGERSTORE_CATALOG_BUILDS;
const sources=ctx.window.FINGERSTORE_CATALOG_SOURCES;
const refs=ctx.window.FINGERSTORE_CATALOG_REFERENCES;
assert(list.length>=490,'historical database should be fully imported, not 100-entry subset');
assert(Object.isFrozen(list),'device catalog should not be mutable');
assert.equal(new Set(Array.from(list,d=>d.id)).size,list.length);
const sourceIds=Array.from(sources,s=>s.id);
assert.deepEqual(sourceIds,['MagiskHidePropsConf','DeviceAnon','PixelProps','ChkDumps','FlashIndex']);
assert(sources.find(s=>s.id==='MagiskHidePropsConf').added>=700);
assert(sources.find(s=>s.id==='DeviceAnon').added>=20);
assert(sources.find(s=>s.id==='PixelProps').added>=40);
assert(refs.some(r=>r.source==='ChkDumps'));
assert(refs.some(r=>r.source==='FlashIndex'));
assert(refs.filter(r=>r.source==='ChkDumps').every(r=>r.fingerprintType!=='global'));
assert(refs.filter(r=>r.source==='FlashIndex').every(r=>r.fingerprintType==='firmware-url'));
const form=/^[^/\s]+\/[^/\s]+\/[^:\s]+:\d+(?:\.\d+)*\/[^/\s]+\/[^:\s]+:user\/release-keys$/;
let variants=0,modern=0,pixel=0,old=0,distinct=new Set();
for(const d of list){
 assert(Object.isFrozen(d));
 assert(Object.isFrozen(d.builds));
 assert(d.brand&&d.device&&d.product&&d.manufacturer&&d.model&&d.label);
 assert(Object.keys(d.builds).includes(d.defaultVersion));
 assert.equal(d.fingerprint,get(d,d.defaultVersion).fingerprint);
 for(const [version,builds] of Object.entries(d.builds)){
  assert(builds.length>0);
  assert(Object.isFrozen(builds));
  assert.equal(all(d,version),builds);
  for(let i=0;i<builds.length;i++){
   const build=builds[i],fp=build.fingerprint;
   assert(Object.isFrozen(build));
   assert(Object.isFrozen(build.sources));
   assert(form.test(fp),'invalid original stock fingerprint: '+fp);
   assert.equal(fp,make(d,version,i));
   assert.equal(fp,get(d,version,i).fingerprint);
   assert.equal(fp.split(':')[1].split('/')[0],version);
   assert(!fp.includes('demo_')&&!fp.includes('/DEMO'));
   if(build.date)assert(/^\d{4}-\d{2}-\d{2}$/.test(build.date));
   if(build.patch)assert(/^\d{4}-\d{2}-\d{2}$/.test(build.patch));
   assert(build.sources.length>0);
   distinct.add(fp);
   if(Number(version)>=13)modern++;
   if(build.sources.includes('PixelProps'))pixel++;
   if(build.sources.includes('MagiskHidePropsConf'))old++;
   variants++;
  }
 }
}
assert(variants>=800,'expected at least 800 original fingerprints, got '+variants);
assert(distinct.size>=800,'all records must represent actual distinct firmware strings');
assert(modern>=40,'require real Android 13–17 fingerprints');
assert(pixel>=40,'OTA-derived Pixel source must be included');
assert(old>=700,'legacy source import missing');
assert(list.some(d=>d.model==='Pixel 5'));
assert(list.some(d=>d.model==='SM-G975F'));
const pixel10=list.find(d=>d.model==='Pixel 10');
assert(pixel10 && pixel10.builds['17'] && make(pixel10,'17').includes(':17/'));
const pixel5=list.find(d=>d.model==='Pixel 5');
assert(!make(pixel5,'17'),'never create future Android version for obsolete device');
assert(!list.some(d=>d.label.includes('Pixel 5 XL')),'fictional device rejected');
assert(page.includes('Google+Sans+Flex'));
assert(page.includes('<md-outlined-select'));
assert(page.includes('Recorded firmware build'));
assert(page.includes('catalogSources'));
assert(!page.includes('id="ssaidTitle"')&&!page.includes('id="keyboxTitle"'));
console.log('PASS: '+list.length+' profiles / '+variants+' sourced fingerprints, real Android 13-17, legacy+OTA+community, five source roles, no fabricated future OS');
